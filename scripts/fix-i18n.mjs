function addKeysToExistingSection(content, sectionName, newKeys) {
  const keyEntries = Object.entries(newKeys);
  
  for (const [key, value] of keyEntries) {
    const keyPattern = new RegExp(`\\s*${key}:\\s*['"]`);
    const sectionPattern = new RegExp(`${sectionName}:\\s*\\{`);
    
    if (!sectionPattern.test(content)) {
      console.log(`  Section ${sectionName} not found for key ${key}`);
      continue;
    }
    
    if (keyPattern.test(content)) {
      console.log(`  Key ${key} already exists in ${sectionName}, skipping`);
      continue;
    }
    
    const sectionStartMatch = content.match(new RegExp(`${sectionName}:\\s*\\{`));
    if (!sectionStartMatch) continue;
    
    const sectionStart = content.indexOf(sectionStartMatch[0]);
    let depth = 0;
    let pos = sectionStart;
    while (pos < content.length) {
      if (content[pos] === '{') depth++;
      if (content[pos] === '}') depth--;
      if (depth === 0) break;
      pos++;
    }
    
    const escapedValue = String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
    const newLine = `\n    ${key}: '${escapedValue}',`;
    content = content.slice(0, pos) + newLine + content.slice(pos);
  }
  
  return content;
}

